/* ── Helper functions ── */

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured);
}

export function getNewArrivals(limit = 8): Product[] {
  return [...products]
    .filter((p) => p.badge === 'NEW' || new Date(p.createdAt) > new Date('2026-06-01'))
    .sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())
    .slice(0, limit);
}

export function getSaleProducts(limit = 8): Product[] {
  return products.filter((p) => p.compareAt && p.compareAt > p.price).slice(0, limit);
}

export function getLowStockProducts(threshold = 5): Product[] {
  return products.filter((p) => p.stock > 0 && p.stock <= threshold);
}

export function getOutOfStockProducts(): Product[] {
  return products.filter((p) => p.stock === 0);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

